"""Build an eval dataset from Claude Code session transcripts.

The premise: a real Claude Code session is a recorded expert doing the same job
we want GAIA to do, on this machine, with this repository. Its answers are a
reference an LLM judge can score against — one nobody had to hand-write, drawn
from work that actually happened rather than from a benchmark author's guess at
what matters.

What this is NOT: a claim that GAIA should reproduce Claude Code's answer word
for word. It is a different agent with a different toolset. The reference sets
the bar for *substance* — did it answer the question that was asked, with the
same grasp of the situation — which is what :mod:`gaia.eval.session_eval` asks
the judge to score.

Transcripts live under ``~/.claude/projects/<slug>/*.jsonl``, one JSON record
per line. Only ``user`` and ``assistant`` records matter here.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, Iterator, List, Optional

#: Where Claude Code keeps its transcripts.
DEFAULT_SESSION_ROOT = Path.home() / ".claude" / "projects"

#: Text that marks a "user" record as machinery rather than something a person
#: typed. Slash-command echoes, tool caveats and injected reminders all arrive
#: on the user channel and none of them are questions anyone asked.
_MACHINERY_MARKERS = (
    "<command-name>",
    "<local-command-stdout>",
    "<local-command-caveat>",
    "<system-reminder>",
    "Caveat: The messages below were generated by the user",
    "[Request interrupted",
    "This session is being continued from a previous conversation",
    # Automation talking to itself: hook feedback, background-task completions
    # and scheduled wake-ups all arrive on the user channel.
    "Stop hook feedback",
    "session-scoped Stop hook",
    "<task-notification>",
    "MONITOR TICK",
    "SYSTEM NOTIFICATION",
    "[Attached image:",  # the reference answer depends on a picture GAIA cannot see
)

#: A prompt longer than this is a pasted dump — a transcript, a stack trace, a
#: whole file — not a question. Its "answer" is unreproducible by design.
MAX_PROMPT_CHARS = 1200

#: A prompt shorter than this is an acknowledgement ("yes", "continue"), not a
#: task worth scoring.
MIN_PROMPT_CHARS = 40

#: An answer shorter than this is a one-liner whose quality a judge cannot
#: meaningfully separate from a coin flip.
MIN_ANSWER_CHARS = 200

#: How much of the previous exchange to carry as context. Enough to make a
#: follow-up answerable, short enough not to hand the agent its own answer.
CONTEXT_PROMPT_CHARS = 400
CONTEXT_ANSWER_CHARS = 900


@dataclass
class SessionTurn:
    """One user prompt and the reference answer it received."""

    id: str
    session: str
    prompt: str
    reference: str
    tools_used: List[str] = field(default_factory=list)
    timestamp: str = ""

    #: What the previous exchange was about. Most of a real session is
    #: follow-ups ("do the same for the other one"), and scoring one of those
    #: without its history measures whether the harness supplied context rather
    #: than whether the agent is any good. The runner replays this first so the
    #: agent under test starts where Claude Code did.
    context: str = ""

    #: Set by the selector, not the extractor — see :func:`select`.
    tags: List[str] = field(default_factory=list)


def _text_of(content: Any) -> str:
    """Flatten an assistant message's content blocks to its visible answer.

    Thinking and tool calls are deliberately dropped: the reference is what the
    user was shown, which is the only part GAIA can be compared against.
    """
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = [
        block.get("text", "")
        for block in content
        if isinstance(block, dict) and block.get("type") == "text"
    ]
    return "\n".join(p for p in parts if p).strip()


def _tools_of(content: Any) -> List[str]:
    if not isinstance(content, list):
        return []
    return [
        str(block.get("name"))
        for block in content
        if isinstance(block, dict) and block.get("type") == "tool_use"
    ]


def _is_machinery(text: str) -> bool:
    return any(marker in text for marker in _MACHINERY_MARKERS)


def iter_records(path: Path) -> Iterator[Dict[str, Any]]:
    """Yield parsed records, skipping lines that are not JSON.

    A truncated final line is normal in a live session — the file is appended to
    while it is being read.
    """
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except ValueError:
                continue


def extract(path: Path) -> List[SessionTurn]:
    """Pair every real user prompt in one transcript with its final answer.

    An assistant "turn" is usually several records — tool calls interleaved with
    text. The reference is the LAST text block of the turn, which is the answer
    the user actually read; earlier text is narration on the way there.
    """
    turns: List[SessionTurn] = []
    pending: Optional[Dict[str, Any]] = None
    answer_parts: List[str] = []
    tools: List[str] = []

    def flush() -> None:
        nonlocal pending, answer_parts, tools
        if pending and answer_parts:
            reference = answer_parts[-1].strip()
            previous = turns[-1] if turns else None
            context = ""
            if previous:
                context = (
                    "Earlier in this session you were asked: "
                    + previous.prompt[:CONTEXT_PROMPT_CHARS]
                    + "\n\nYou answered: "
                    + previous.reference[:CONTEXT_ANSWER_CHARS]
                )
            turns.append(
                SessionTurn(
                    id=f"{path.stem[:8]}-{len(turns):03d}",
                    session=path.stem,
                    prompt=pending["prompt"],
                    reference=reference,
                    tools_used=sorted(set(tools)),
                    timestamp=pending.get("timestamp", ""),
                    context=context,
                )
            )
        pending, answer_parts, tools = None, [], []

    for record in iter_records(path):
        # Subagent transcripts are a different conversation; their prompts were
        # written by an agent, not by the user.
        if record.get("isSidechain"):
            continue
        message = record.get("message")
        if not isinstance(message, dict):
            continue

        if record.get("type") == "user":
            content = message.get("content")
            text = content.strip() if isinstance(content, str) else ""
            # A user record with block content is a tool RESULT being fed back,
            # not a person typing.
            if not text or _is_machinery(text):
                continue
            flush()
            pending = {"prompt": text, "timestamp": record.get("timestamp", "")}

        elif record.get("type") == "assistant" and pending:
            if text := _text_of(message.get("content")):
                answer_parts.append(text)
            tools.extend(_tools_of(message.get("content")))

    flush()
    return turns


def discover(root: Path = DEFAULT_SESSION_ROOT, project: str = "") -> List[Path]:
    """Every transcript under *root*, newest first, optionally one project."""
    if not root.is_dir():
        return []
    pattern = f"{project}/*.jsonl" if project else "*/*.jsonl"
    return sorted(root.glob(pattern), key=lambda p: p.stat().st_mtime, reverse=True)


#: Prompts whose answer depends on conversation the agent under test never had
#: ("do that for the other one too"). Scoring those measures the harness, not
#: the agent.
_CONTEXT_DEPENDENT = re.compile(
    r"^\s*(also|and|then|now|next|ok|okay|yes|no|continue|same|do that|try again)\b",
    re.IGNORECASE,
)

#: Prompts that ask for a destructive or irreversible action. Replaying a real
#: session means replaying real instructions, and an eval usually runs with
#: confirmations off — "lets commit and push those changes" and "discard any
#: local changes" both appeared in the first ten cases drawn from these
#: transcripts. Nothing happened, because the shell refuses git writes
#: (SAFE_GIT_COMMANDS), but that is a defence we happen to have rather than one
#: this recipe arranged. A benchmark must not be able to mutate the machine it
#: is measuring.
_DESTRUCTIVE = re.compile(
    r"\b(push|commit|merge|rebase|reset|revert|discard|delete|remove|rm|drop|"
    r"uninstall|overwrite|force|publish|deploy|release)\b",
    re.IGNORECASE,
)


#: Rough topic tags, used only to spread the sample across kinds of work.
_TAGS = {
    "code": ("code", "function", "bug", "test", "refactor", "implement", "fix"),
    "repo": ("repo", "commit", "branch", "pr ", "pull request", "git"),
    "explain": ("what is", "how does", "why", "explain", "difference"),
    "search": ("find", "search", "where", "look for", "locate"),
    "docs": ("document", "readme", "docs", "write up", "report"),
}


def _tags_for(prompt: str) -> List[str]:
    low = prompt.lower()
    return sorted(tag for tag, words in _TAGS.items() if any(w in low for w in words))


def select(
    turns: Iterable[SessionTurn],
    limit: int = 10,
    min_prompt: int = MIN_PROMPT_CHARS,
    min_answer: int = MIN_ANSWER_CHARS,
) -> List[SessionTurn]:
    """Pick a spread of self-contained, substantive turns.

    Self-contained matters more than it sounds: most of a real session is
    follow-ups, and a follow-up scored without its history measures whether the
    harness supplied context, not whether the agent is any good.
    """
    candidates = [
        turn
        for turn in turns
        if min_prompt <= len(turn.prompt) <= MAX_PROMPT_CHARS
        and len(turn.reference) >= min_answer
        and not _CONTEXT_DEPENDENT.match(turn.prompt)
        and not _DESTRUCTIVE.search(turn.prompt)
    ]
    for turn in candidates:
        turn.tags = _tags_for(turn.prompt)

    # Round-robin across tags so ten questions are not ten of the same question.
    by_tag: Dict[str, List[SessionTurn]] = {}
    for turn in candidates:
        by_tag.setdefault(turn.tags[0] if turn.tags else "other", []).append(turn)
    for bucket in by_tag.values():
        bucket.sort(key=lambda t: len(t.reference), reverse=True)

    chosen: List[SessionTurn] = []
    while len(chosen) < limit and any(by_tag.values()):
        for bucket in by_tag.values():
            if bucket and len(chosen) < limit:
                chosen.append(bucket.pop(0))
    return chosen


def build_dataset(
    root: Path = DEFAULT_SESSION_ROOT,
    project: str = "",
    limit: int = 10,
) -> Dict[str, Any]:
    """Extract, select and package a dataset ready for the runner."""
    paths = discover(root, project)
    turns: List[SessionTurn] = []
    for path in paths:
        turns.extend(extract(path))
    chosen = select(turns, limit=limit)
    return {
        "source": "claude-code-sessions",
        "sessions_scanned": len(paths),
        "turns_extracted": len(turns),
        "cases": [asdict(turn) for turn in chosen],
    }
