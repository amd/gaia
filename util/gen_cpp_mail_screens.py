MAX_CP = 0x110000


def _chars():
    for cp in range(MAX_CP):
        if 0xD800 <= cp < 0xE000:
            continue
        yield cp, chr(cp)


def _c_string(text: str) -> str:
    out = []
    for byte in text.encode("utf-8"):
        if 0x20 <= byte < 0x7F and chr(byte) not in '"\\?':
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02x}")
    # A hex escape swallows following hex digits, so split the literal after one.
    joined = ""
    for i, piece in enumerate(out):
        if i and out[i - 1].startswith("\\x") and re.match(r"[0-9a-fA-F]", piece):
            joined += '" "'
        joined += piece
    return '"' + joined + '"'


def _ranges(cps: List[int]) -> List[List[int]]:
    ranges: List[List[int]] = []
    for cp in cps:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges


def _emit_ranges(name: str, cps: List[int]) -> str:
    rows = ", ".join(f"{{0x{a:x}, 0x{b:x}}}" for a, b in _ranges(cps))
    return f"constexpr CpRange {name}[] = {{{rows}}};\n"


def _emit_map(name: str, pairs: List[tuple]) -> str:
    rows = ",\n".join(f"    {{0x{cp:x}, {_c_string(text)}}}" for cp, text in pairs)
    return f"constexpr CpText {name}[] = {{\n{rows}\n}};\n"


def generate_tables() -> str:
    marker, lower, lt, gt, invisible, word, digit, space = [], [], [], [], [], [], [], []
    sigma_cased, case_ignorable, unprintable = [], [], []
    for cp, ch in _chars():
        # Final sigma: str.lower skips case-ignorable code points around a
        # capital sigma and asks whether a cased one stands there.
        stops_cased = (ch + "\u03a3").lower()[-1] == "\u03c2"
        if stops_cased:
            sigma_cased.append(cp)
        elif ("A" + ch + "\u03a3").lower()[-1] == "\u03c2":
            case_ignorable.append(cp)
        if not ch.isprintable():
            unprintable.append(cp)
        folded = untrusted_text._marker_letters(ch)
        if folded:
            marker.append((cp, folded))
        if ch.lower() != ch:
            lower.append((cp, ch.lower()))
        side = untrusted_text._fence_side(ch)
        if side == "<":
            lt.append(cp)
        elif side == ">":
            gt.append(cp)
        if untrusted_text.fence_run_invisible(ch):
            invisible.append(cp)
        if re.fullmatch(r"\w", ch):
            word.append(cp)
        if re.fullmatch(r"\d", ch):
            digit.append(cp)
        if re.fullmatch(r"\s", ch):
            assert ch.isspace()
            space.append(cp)
        elif ch.isspace():
            raise SystemExit(f"re \\s and str.isspace disagree on U+{cp:04X}")
    ignorecase = []
    for letter in "abcdefghijklmnopqrstuvwxyz":
        for cp, ch in _chars():
            if ch != letter and re.fullmatch(letter, ch, re.IGNORECASE):
                ignorecase.append((cp, letter))
    ignorecase.sort()
    entities = sorted(html.entities.html5.items())
    invalid_charrefs = sorted(html._invalid_charrefs.items())

    parts = [
        "// Generated by util/gen_cpp_mail_screens.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n",
        "// Each table mirrors one Python behaviour the mail screens depend on.\n\n",
        "// untrusted_text._marker_letters(chr(cp)) where non-empty.\n",
        _emit_map("kMarkerLetters", marker),
        "// chr(cp).lower() where it differs.\n",
        _emit_map("kLower", lower),
        "// untrusted_text._fence_side(chr(cp)) == '<' / '>'.\n",
        _emit_ranges("kFenceLt", lt),
        _emit_ranges("kFenceGt", gt),
        "// untrusted_text.fence_run_invisible(chr(cp)).\n",
        _emit_ranges("kFenceInvisible", invisible),
        "// re's \\w, \\d and \\s on str patterns (\\s equals str.isspace).\n",
        _emit_ranges("kWord", word),
        _emit_ranges("kDigit", digit),
        _emit_ranges("kSpace", space),
        "// str.lower's final-sigma context: cased and not case-ignorable / case-ignorable.\n",
        _emit_ranges("kSigmaCased", sigma_cased),
        _emit_ranges("kCaseIgnorable", case_ignorable),
        "// not str.isprintable(), for repr().\n",
        _emit_ranges("kUnprintable", unprintable),
        "// Non-identical code points re.IGNORECASE matches to each ASCII letter.\n",
        _emit_map("kIgnoreCase", ignorecase),
        "// html.entities.html5, sorted by name.\n",
        "constexpr NameText kHtml5[] = {\n"
        + ",\n".join(f"    {{{_c_string(k)}, {_c_string(v)}}}" for k, v in entities)
        + "\n};\n",
        "// html._invalid_charrefs.\n",
        _emit_map("kInvalidCharrefs", invalid_charrefs),
        "// html._invalid_codepoints.\n",
        _emit_ranges("kInvalidCodepoints", sorted(html._invalid_codepoints)),
    ]
    return "".join(parts)


