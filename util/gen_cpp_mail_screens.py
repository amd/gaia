class Mail:
    def __init__(self, mid, thread, *, sender, to=USER, cc="", subject="Subject",
                 body="", age_days=1.0, labels=None, html=False, draft=False, row=None):
        self.row = row
        self.mid, self.thread, self.sender, self.to, self.cc = mid, thread, sender, to, cc
        self.subject, self.body, self.html, self.draft = subject, body, html, draft
        self.ms = int(NOW_MS - age_days * DAY_MS)
        self.labels = list(labels or ["INBOX"])


def outbound(mid, thread, *, to, body, age_days, subject="Re:"):
    return Mail(mid, thread, sender=f"Me <{USER}>", to=to, subject=subject, body=body,
                age_days=age_days, labels=["SENT"])


def _iso(ms: int) -> str:
    from datetime import datetime, timezone
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class RecordingBackend:
    """The Gmail backend's answers for `mails`, recorded for replay."""

    def __init__(self, mails, *, truncated_threads=()):
        self.mails = mails
        self.truncated_threads = set(truncated_threads)
        self.lists: Dict[str, Any] = {}
        self.threads: Dict[str, Any] = {}

    def get_user_email(self):
        return USER.upper()

    def list_thread_ids(self, folder, *, limit=50):
        label = {"inbox": "INBOX", "sent": "SENT"}[folder]
        hits = sorted((m for m in self.mails if label in m.labels), key=lambda m: m.ms,
                      reverse=True)
        ids: List[str] = []
        for m in hits[:limit]:
            if m.thread not in ids:
                ids.append(m.thread)
        page = hits[:limit]
        result = {"thread_ids": ids, "messages_listed": len(page),
                  "truncated": len(hits) > limit or len(page) >= limit}
        self.lists[f"{folder}:{limit}"] = result
        return result

    def get_thread(self, thread_id):
        msgs = sorted((m for m in self.mails if m.thread == thread_id), key=lambda m: m.ms)
        messages = []
        for m in msgs:
            summary = {
                "id": m.mid, "thread_id": m.thread, "subject": m.subject or "(no subject)",
                "from": m.sender, "to": m.to, "cc": m.cc, "received": _iso(m.ms),
                "unread": False, "flagged": False, "categories": [], "preview": m.body[:80],
                "has_attachments": False, "attachments": [],
                "auto_submitted": "auto-replied" if "AUTO_REPLY" in m.labels else "",
                "x_autoreply": "yes" if "X_AUTOREPLY" in m.labels else "",
                "body": m.body, "body_content_type": "html" if m.html else "text",
                "draft": m.draft, "_label_ids": list(m.labels),
            }
            messages.append(summary)
        result = {"thread_id": thread_id, "messages": messages,
                  "truncated": thread_id in self.truncated_threads}
        self.threads[thread_id] = result
        return result


