def _mail_record(m: Mail) -> Dict[str, Any]:
    record: Dict[str, Any] = {"id": m.mid, "thread": m.thread, "to": m.to, "cc": m.cc,
                              "ms": m.ms, "received": _iso(m.ms), "labels": m.labels}
    if m.row:
        record["row"] = m.row
    else:
        record.update(sender=m.sender, subject=m.subject, body=m.body)
    if m.html:
        record["html"] = True
    if m.draft:
        record["draft"] = True
    return record


def _drop_corpus_text(expected, mails) -> None:
    """A corpus message in `latest_messages` keeps only its id; the test refills it."""
    if not expected:
        return
    rows = {m.mid for m in mails if m.row}
    expected["latest_messages"] = [
        {"id": m["id"], "corpus": True} if m["id"] in rows else m
        for m in expected["latest_messages"]
    ]


def scan_cases(rng: random.Random, corpus) -> List[Dict[str, Any]]:
    out = []
    for scenario in _scenarios(rng, corpus):
        kwargs = dict(scenario["kwargs"])
        bad = kwargs.pop("bad_received", None)
        backend = RecordingBackend(scenario["mails"],
                                   truncated_threads=scenario.get("truncated_threads", ()))
        max_inbox = kwargs.get("max_inbox", waiting.DEFAULT_MAX_INBOX_SCAN)
        min_age = kwargs.get("min_age_hours", 0)
        if bad:
            original = backend.get_thread

            def broken(tid, original=original):
                result = original(tid)
                for m in result["messages"]:
                    if m["id"] == bad:
                        m["received"] = "yesterday"
                return result

            backend.get_thread = broken
        case: Dict[str, Any] = {"name": scenario["name"], "max_inbox": max_inbox,
                                "min_age_hours": min_age}
        try:
            case["expected"] = waiting.detect_waiting_on_you(
                backend, max_inbox=max_inbox, min_age_hours=min_age, now_ms=NOW_MS)
        except MailboxError as exc:
            case.update(_error(exc))
        case["user"] = backend.get_user_email()
        case["truncated_threads"] = sorted(backend.truncated_threads)
        case["bad_received"] = bad
        case["mails"] = [_mail_record(m) for m in scenario["mails"]]
        _drop_corpus_text(case.get("expected"), scenario["mails"])
        out.append(case)
    return out


