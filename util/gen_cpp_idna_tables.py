"""Generate gaiacpp's IDNA tables and the address parity fixture.

``person_approval.sendable_address`` sends an international domain through
``idna.encode(domain, uts46=True)``, which reads the ``idna`` package's own
Unicode tables and Python's ``unicodedata`` (NFC, categories, bidi classes,
combining classes, names). C++ has none of these, so this script writes them
out as data:

- ``cpp/src/idna_tables.inc``: the tables ``cpp/src/idna.cpp`` reads.
- ``cpp/tests/fixtures/calendar/address_parity.json``: addresses with what
  ``sendable_address`` returns or raises for each, which the C++ tests replay.

Run from the repo root with the project's Python: ``python util/gen_cpp_idna_tables.py``.
``tests/unit/test_gaiacpp_idna_tables.py`` checks the committed tables against
the running Python when its versions match the ones recorded here.
"""

from __future__ import annotations

import json
import random
import sys
import unicodedata
from pathlib import Path
from typing import Dict, List, Tuple

import idna
from idna import idnadata, uts46data

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from gaia.agents.base import person_approval  # noqa: E402

TABLES = ROOT / "cpp" / "src" / "idna_tables.inc"
PARITY = ROOT / "cpp" / "tests" / "fixtures" / "calendar" / "address_parity.json"
SURROGATES = range(0xD800, 0xE000)
ALL = [cp for cp in range(0x110000) if cp not in SURROGATES]


def header() -> str:
    return (
        f"// Generated by util/gen_cpp_idna_tables.py from Python {sys.version.split()[0]} "
        f"(unicodedata {unicodedata.unidata_version}) and idna {idna.__version__} "
        f"(idnadata {idnadata.__version__}). Do not edit.\n"
    )


def u32(text: str) -> str:
    return 'U"' + "".join(f"\\U{ord(c):08X}" for c in text) + '"'


def runs(points: List[int]) -> List[Tuple[int, int]]:
    out: List[Tuple[int, int]] = []
    for cp in points:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def intranges(ranges) -> List[Tuple[int, int]]:
    return [(r >> 32, (r & 0xFFFFFFFF) - 1) for r in ranges]


def range_table(name: str, comment: str, ranges: List[Tuple[int, int]]) -> str:
    rows = "".join(f"    {{0x{lo:X}, 0x{hi:X}}},\n" for lo, hi in ranges)
    return f"// {comment}\nconstexpr IdnaRange {name}[] = {{\n{rows}}};\n\n"


def valued_runs(value_of) -> List[Tuple[int, int, object]]:
    out: List[Tuple[int, int, object]] = []
    for cp in ALL:
        value = value_of(cp)
        if out and out[-1][2] == value and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp, value)
        else:
            out.append((cp, cp, value))
    return out


def tables() -> str:
    parts = [header(), "\n"]

    rows = []
    for start, status, replacement in zip(
        uts46data.uts46_starts, uts46data.uts46_statuses, uts46data.uts46_replacements
    ):
        text = "nullptr" if replacement is None else u32(replacement)
        rows.append(f"    {{0x{start:X}, '{chr(status)}', {text}}},\n")
    parts.append(
        "// idna.uts46data: from each start, status V/M/D/I/X and the mapping.\n"
        "constexpr IdnaMap kUts46[] = {\n" + "".join(rows) + "};\n\n"
    )

    for cls in ("PVALID", "CONTEXTJ", "CONTEXTO"):
        name = "k" + cls.capitalize().replace("Contextj", "ContextJ").replace(
            "Contexto", "ContextO"
        )
        parts.append(
            range_table(
                name,
                f"idnadata.codepoint_classes['{cls}']",
                intranges(idnadata.codepoint_classes[cls]),
            )
        )
    for jt in ("D", "L", "R", "T"):
        parts.append(
            range_table(
                f"kJoining{jt}",
                f"idnadata.joining_types['{jt}']",
                intranges(idnadata.joining_types[jt]),
            )
        )
    for script in ("Greek", "Han", "Hebrew", "Hiragana", "Katakana"):
        parts.append(
            range_table(
                f"kScript{script}",
                f"idnadata.scripts['{script}']",
                intranges(idnadata.scripts[script]),
            )
        )

    marks = [cp for cp in ALL if unicodedata.category(chr(cp))[0] == "M"]
    parts.append(
        range_table("kMarks", "unicodedata.category(c)[0] == 'M'", runs(marks))
    )
    unnamed = [
        cp
        for cp in ALL
        if unicodedata.combining(chr(cp)) == 0
        and unicodedata.name(chr(cp), None) is None
    ]
    parts.append(
        range_table(
            "kUnnamed",
            "combining class 0 and no unicodedata.name: idna's _combining_class raises",
            runs(unnamed),
        )
    )

    bidi = valued_runs(lambda cp: unicodedata.bidirectional(chr(cp)))
    rows = "".join(
        f'    {{0x{lo:X}, 0x{hi:X}, "{value}"}},\n' for lo, hi, value in bidi if value
    )
    parts.append(
        "// unicodedata.bidirectional; a code point in no row has none ('').\n"
        "constexpr IdnaBidi kBidi[] = {\n" + rows + "};\n\n"
    )

    ccc = valued_runs(lambda cp: unicodedata.combining(chr(cp)))
    rows = "".join(
        f"    {{0x{lo:X}, 0x{hi:X}, {value}}},\n" for lo, hi, value in ccc if value
    )
    parts.append(
        "// unicodedata.combining, where it isn't 0.\n"
        "constexpr IdnaCcc kCombining[] = {\n" + rows + "};\n\n"
    )

    hangul = range(0xAC00, 0xD7A4)
    rows = []
    for cp in ALL:
        if cp in hangul:
            continue
        nfd = unicodedata.normalize("NFD", chr(cp))
        if nfd != chr(cp):
            rows.append(f"    {{0x{cp:X}, {u32(nfd)}}},\n")
    parts.append(
        "// unicodedata.normalize('NFD', c) where it changes c, Hangul syllables aside.\n"
        "constexpr IdnaDecomposition kDecompositions[] = {\n" + "".join(rows) + "};\n\n"
    )

    pairs: List[Tuple[int, int, int]] = []
    for cp in ALL:
        if cp in hangul:
            continue
        decomposition = unicodedata.decomposition(chr(cp))
        if not decomposition or decomposition.startswith("<"):
            continue
        parts_of = [int(x, 16) for x in decomposition.split()]
        if len(parts_of) != 2 or unicodedata.normalize("NFC", chr(cp)) != chr(cp):
            continue
        pairs.append((parts_of[0], parts_of[1], cp))
    pairs.sort()
    rows = "".join(f"    {{0x{a:X}, 0x{b:X}, 0x{c:X}}},\n" for a, b, c in pairs)
    parts.append(
        "// Primary composites: the canonical pair each composes from, in order.\n"
        "constexpr IdnaComposition kCompositions[] = {\n" + rows + "};\n"
    )
    return "".join(parts)


def outcome(address: str) -> Dict[str, str]:
    try:
        return {
            "address": address,
            "sent": person_approval.sendable_address(address, "notify_attendees"),
        }
    except ValueError as exc:
        return {"address": address, "error": str(exc)}


