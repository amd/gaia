def fixture() -> Dict[str, object]:
    nfc_inputs = [
        "é",
        "ạ̈",
        "각",
        "Å",
        "क़",
        "ḍ̇",
        "ཱི",
        "\U0001d15e",
        "q̣̇",
    ]
    rng = random.Random(9221)
    marks = [cp for cp in ALL if unicodedata.combining(chr(cp))]
    bases = [
        cp for cp in ALL if unicodedata.decomposition(chr(cp))[:1] not in ("", "<")
    ]
    for _ in range(500):
        text = chr(rng.choice(bases)) + "".join(
            chr(rng.choice(marks)) for _ in range(rng.randint(0, 3))
        )
        nfc_inputs.append(
            unicodedata.normalize("NFD", text) if rng.random() < 0.5 else text
        )
    return {
        "_comment": "Generated by util/gen_cpp_idna_tables.py. Do not edit.",
        "python": sys.version.split()[0],
        "unidata": unicodedata.unidata_version,
        "idna": idna.__version__,
        "addresses": [outcome("bob@" + domain) for domain in samples()],
        "nfc": [[text, unicodedata.normalize("NFC", text)] for text in nfc_inputs],
    }


def main() -> None:
    TABLES.write_text(tables(), encoding="utf-8", newline="\n")
    PARITY.write_text(
        json.dumps(fixture(), ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
