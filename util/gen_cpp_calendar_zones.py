"""Generate cpp/src/calendar_win_zones.inc: Windows time zone names to IANA names.

Outlook may name a zone the Windows way ("Pacific Standard Time"), and the
Python calendar tools read it through ``tzlocal.windows_tz.win_tz``. gaiacpp
reads the same table, written out here as data.

Run from the repo root with the project's Python: ``python util/gen_cpp_calendar_zones.py``.
"""

from pathlib import Path

from tzlocal.windows_tz import win_tz

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "cpp" / "src" / "calendar_win_zones.inc"


def main() -> None:
    lines = [
        "// Generated by util/gen_cpp_calendar_zones.py from tzlocal.windows_tz.win_tz. Do not edit.",
        "// clang-format off",
    ]
    for windows, iana in sorted(win_tz.items()):
        lines.append(f'{{"{windows}", "{iana}"}},')
    lines.append("// clang-format on")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(win_tz)} zones to {TARGET}")


if __name__ == "__main__":
    main()
