"""Write the look-alike tables used by the fence-marker name check.

The core check (``src/gaia/agents/base/lookalikes.py``) and the email hub
agent's copy (``hub/agents/email/python/gaia_agent_email/tools/lookalikes.py``)
are generated from Unicode's ``confusables.txt`` (UTS #39), so the two stay
identical and the data can be refreshed for a new Unicode version:

    python util/gen_lookalikes.py path/to/confusables.txt

Only single code points whose UTS #39 prototype is made of ASCII letters and
digits are kept, and only where NFKC with case folding doesn't already give the
same letters. Characters NFKC changes are left to NFKC, which the check applies
first.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path
from typing import Dict, List

REPO = Path(__file__).resolve().parents[1]
TARGETS = (
    REPO / "src/gaia/agents/base/lookalikes.py",
    REPO / "hub/agents/email/python/gaia_agent_email/tools/lookalikes.py",
)
WIDTH = 88


def _parse(path: Path):
    text = path.read_text(encoding="utf-8-sig")
    version = re.search(r"^# Version: (\S+)", text, re.MULTILINE)
    pairs = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        source, prototype, _ = (field.strip() for field in line.split(";"))
        if " " in source:
            continue
        pairs.append(
            (chr(int(source, 16)), "".join(chr(int(c, 16)) for c in prototype.split()))
        )
    return (version.group(1) if version else "unknown"), pairs


def _alnum_ascii(text: str) -> bool:
    return bool(text) and all(c.isascii() and c.isalnum() for c in text)


def _ascii_fold(pairs) -> Dict[str, str]:
    """UTS #39's own ASCII entries, case folded: ``m`` reads as ``rn``, and so on."""
    fold: Dict[str, str] = {}
    for source, prototype in pairs:
        if not source.isascii():
            continue
        key = source.casefold()
        value = "".join(c for c in prototype.casefold() if c.isascii() and c.isalnum())
        if key.isalnum() and value and value != key:
            fold[key] = value
    return dict(sorted(fold.items()))


def _letters(text: str, fold: Dict[str, str]) -> str:
    folded = unicodedata.normalize("NFKC", text).casefold()
    return "".join(fold.get(c, c) for c in folded if c.isascii() and c.isalnum())


def _by_prototype(pairs, fold: Dict[str, str]) -> Dict[str, str]:
    groups: Dict[str, List[str]] = {}
    for source, prototype in pairs:
        if source.isascii() or unicodedata.normalize("NFKC", source) != source:
            continue
        prototype = unicodedata.normalize("NFKC", prototype)
        if not _alnum_ascii(prototype):
            continue
        if _letters(source, fold) == _letters(prototype, fold):
            continue
        groups.setdefault(prototype, []).append(source)
    return {
        key: "".join(sorted(chars))
        for key, chars in sorted(
            groups.items(), key=lambda item: (item[0].casefold(), item[0])
        )
    }


def _escape(chars: str) -> str:
    return "".join(
        f"\\u{ord(c):04x}" if ord(c) <= 0xFFFF else f"\\U{ord(c):08x}" for c in chars
    )


def _render(version: str, groups: Dict[str, str], fold: Dict[str, str]) -> str:
    lines = [
        "# Copyright(C) 2025-2026 Advanced Micro Devices, Inc. All rights reserved.",
        "# SPDX-License-Identifier: MIT",
        '"""Characters that read as ASCII letters or digits, for the fence-marker check.',
        "",
        f"Generated by ``util/gen_lookalikes.py`` from Unicode confusables.txt {version}",
        "(UTS #39). Do not edit by hand: regenerate, which rewrites the core and email",
        "hub agent copies together.",
        '"""',
        "",
        "from typing import Dict",
        "",
        "# Each UTS #39 prototype, with the characters that read as it.",
        "_BY_PROTOTYPE: Dict[str, str] = {",
    ]
    for prototype, chars in groups.items():
        escaped = _escape(chars)
        head = f'    "{prototype}": '
        if len(head) + len(escaped) + 3 <= WIDTH:
            lines.append(f'{head}"{escaped}",')
            continue
        lines.append(f"{head}(")
        room = WIDTH - 10
        step = room - room % 6
        chunk = ""
        for piece in re.findall(r"\\u[0-9a-f]{4}|\\U[0-9a-f]{8}", escaped):
            if len(chunk) + len(piece) > step:
                lines.append(f'        "{chunk}"')
                chunk = ""
            chunk += piece
        lines.append(f'        "{chunk}"')
        lines.append("    ),")
    lines += [
        "}",
        "",
        "# A non-ASCII character that reads as ASCII letters, mapped to them.",
        "LOOKALIKES: Dict[str, str] = {",
        "    char: prototype for prototype, chars in _BY_PROTOTYPE.items() for char in chars",
        "}",
        "",
        "# UTS #39's own ASCII entries, case folded, so ``m`` and ``rn`` compare equal",
        "# and so do ``i``, ``l`` and ``1``.",
        "ASCII_FOLD: Dict[str, str] = {",
    ]
    lines += [f'    "{key}": "{value}",' for key, value in fold.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: List[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    version, pairs = _parse(Path(argv[1]))
    fold = _ascii_fold(pairs)
    source = _render(version, _by_prototype(pairs, fold), fold)
    for target in TARGETS:
        target.write_text(source, encoding="utf-8")
        print(f"wrote {target.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
